"""Статический блок требований к `review.json` (§4.4, [DESIGN-004]).

Одна из опор анти-галлюцинационного контура: те же четыре правила
оркестратор применяет к вердикту на валидации. Промпт обязан сообщать их
заранее и дословно — иначе ревьюер узнаёт о требовании только из ошибки
валидации и платит за это ретраем.

Почему константы, а не функция. Текст не зависит ни от раунда, ни от
артефактов: правила §4.4 одинаковы для любого ревью. Функция-обёртка
создала бы иллюзию параметризации и место, куда однажды просочится
состояние; константы импортируются напрямую и по построению дают одни и
те же байты в любом запуске (NFR-002).

Констант две, а текст один. Единственное, чем требования к develop- и
doc-ревью различаются, — **тег схемы артефакта**: `review.json`
develop/analyze-сессии несёт `disputatio/v1`, doc-сессии — `disputatio/v2`
(§5.1 SPEC-002; поля `checklist` и `defect_class` под v1 отвергаются
схемой, см. `contracts/review.py`). Различие подставляется в общий шаблон
на импорте — обе константы остаются готовыми строками, а формулировки
правил не раздваиваются.

Формулировки живут здесь и только здесь: `reviewer.py` и `doc_reviewer.py`
вставляют свой блок целиком, не пересказывая его своими словами.
Расхождение промпта с валидатором обошлось бы дороже, чем это единственное
место правды — тем более что `runtime/steps.py::_accepted_review` судит
doc-ревью ровно теми же четырьмя правилами §4.4.
"""

from typing import Final

from disputatio.contracts.base import SCHEMA_V1, SCHEMA_V2

_REQUIREMENTS_TEMPLATE: Final[str] = (
    "## Требования к выводу: `review.json` (§4.4)\n"
    "Ответ обязан быть валидным `review.json` схемы `{schema}`. "
    "Оркестратор проверяет его машинно; у каждого правила ниже своё "
    "последствие — повтор шага или понижение замечания, оно названо в "
    "самом правиле.\n"
    "- Вердикт `request_changes` или `reject` ⇒ список `issues` непуст и "
    "содержит хотя бы одно замечание severity `blocker` или `major`: "
    "«нужны правки» без блокирующего замечания не принимается.\n"
    "- Замечание severity `blocker` или `major` обязано нести непустой "
    "`evidence` — цитату diff, вывод команды или ссылку на gate из "
    "`verification.json`. Без него оркестратор не отклоняет ревью, а "
    "понижает замечание до `minor`: голословный блокер не должен крутить "
    "цикл. Понижение выполняется до проверки правила выше, поэтому "
    "понижённое замечание негативный вердикт уже не удержит.\n"
    "- Вердикт `approve` запрещён, если `verification.overall == fail`: "
    "«одобряю, но проверки красные» — противоречие, такой вердикт "
    "отвергается на валидации.\n"
    "- Список `checked` обязателен и непуст: перечислите, что вы реально "
    "проверили — какие файлы прочитали, какие команды запустили, что "
    "увидели. Пустой список означает, что ревью не принято и шаг "
    "повторяется."
)

#: Блок для промпта ревьюера develop/analyze-раунда (`reviewer.py`).
REVIEW_SCHEMA_REQUIREMENTS: Final[str] = _REQUIREMENTS_TEMPLATE.format(schema=SCHEMA_V1)

#: Тот же блок под тегом doc-артефакта (`doc_reviewer.py`, §5.1 SPEC-002).
DOC_REVIEW_SCHEMA_REQUIREMENTS: Final[str] = _REQUIREMENTS_TEMPLATE.format(
    schema=SCHEMA_V2
)
