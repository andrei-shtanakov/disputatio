"""Учёт бюджета сессии ([DESIGN-009], [REQ-009]).

`budget_used` — единственный вход стоп-условия BUDGET_HIT (§5.2), и ошибиться
в нём можно двумя противоположными способами. Приравняй «адаптер не сообщил
расход» к «адаптер сообщил ноль» — и на адаптере без token-метрик счётчик
замрёт: сессия будет жечь бюджет вечно, формально его соблюдая. Прими
сообщённый ноль за отсутствие данных — и потеряешь уже накопленное. Поэтому
различие «сообщил / не сообщил» выражено отдельным швом (`token_delta`): в
`BudgetUsed` для неизвестности места нет (`tokens: int`), и стереть её можно
молча.

Вторая половина модуля — про порядок. `SessionState` frozen, а `SessionFsm`
владеет своим состоянием и публичного мутатора бюджета не имеет (менять ядро
— вне scope), поэтому начисление это **пересадка FSM**: `store.save` нового
состояния, затем новый `SessionFsm` с ним. Два правила порядка, и оба
наблюдаемы только логом вызовов:

1. **Сначала диск, потом память** — тот же write-ahead, что у перехода (I2).
   Создай FSM раньше записи, и обрыв между ними оставил бы на диске
   состояние, из которого сессия уже ушла, то есть потерянный расход.
2. **Пересадка — только после `handle_step_success`** (ADR-004). Счётчик
   schema-повторов принадлежит экземпляру FSM и начинается с нуля у нового:
   пересадка посреди шага обнулила бы лимит I4 на каждой попытке и
   превратила `schema_retries` в бесконечность.

Отсюда же два сознательных умолчания. Начислять нечего — писать нечего:
состояние, не изменившееся от начисления, на диск не переписывается и FSM не
пересаживает, поэтому «шаг без расхода и без времени» не оставляет следа
вовсе, а не сочиняет запись о нуле. И шаг, не дошедший до конца (исчерпанные
повторы, упавший порт), бюджета не начисляет: расход провалившихся попыток
теряется, но сессия к этому моменту уже `FAILED`, и считать её бюджет некому.
"""

from typing import TYPE_CHECKING

from disputatio.contracts import AgentTurn, SessionState
from disputatio.core import SessionFsm

if TYPE_CHECKING:  # pragma: no cover - только для аннотации, импорта нет
    from disputatio.runtime.steps import StepContext


def charge_step(
    ctx: "StepContext", *, turn: AgentTurn | None, elapsed_s: float
) -> "StepContext":
    """Начисляет бюджет завершённого шага и пересаживает FSM на новое состояние.

    Возвращает контекст, с которым цикл продолжает работу: тот же самый, если
    начислять было нечего, и новый — с новым `SessionFsm` — если бюджет
    изменился. Второго способа обновить бюджет у runtime нет: состояние
    frozen, а мутатора у FSM не существует.

    Порядок внутри — `save`, затем конструктор FSM, и никакой третьей строки
    между ними: состояние, с которым цикл продолжает работать, обязано уже
    лежать на диске (I2). Оба объекта получают ОДНО значение, а не две копии
    одного смысла, — разойдись они, write-ahead выполнялся бы формально.

    Вызывается ровно на границе шага, после `handle_step_success` (ADR-004):
    внутри retry-петли новый FSM обнулил бы счётчик повторов текущего шага.
    Гарантия структурная — начисление физически не может случиться раньше,
    чем шаг вернул управление.
    """
    charged = accumulate(ctx.fsm.state, turn=turn, elapsed_s=elapsed_s)
    if charged == ctx.fsm.state:
        return ctx

    ctx.deps.store.save(charged)
    return ctx.with_fsm(
        SessionFsm(
            charged,
            store=ctx.deps.store,
            sink=ctx.deps.sink,
            now=ctx.deps.now,
        )
    )


def accumulate(
    state: SessionState, *, turn: AgentTurn | None, elapsed_s: float
) -> SessionState:
    """Возвращает копию состояния с обновлённым `budget_used` ([REQ-009]).

    `turn.tokens_used is None` — «адаптер не сообщил»: счётчик не растёт и
    неизвестность НЕ выдаётся за ноль. `tokens_used == 0` — сообщённый ноль:
    прибавляется как 0, что наблюдаемо тем, что счётчик не становится `None`
    и не теряет предыдущее значение. `turn is None` — шаг без разговора с
    агентом (`VERIFYING`, `DECIDING`): токенов он не тратит, а время тратит.

    `elapsed_s` берётся из монотонных часов сессии (`deps.monotonic`) и
    поэтому неотрицателен — отсюда `wall_seconds` не убывает ни на одном
    шаге ([REQ-009]). Собственной проверки знака здесь нет: гарантию даёт
    источник времени, а не ветка, которую можно инвертировать.

    Вход не мутируется: `SessionState` frozen, история раундов
    append-only, и правка состояния на месте лишила бы вызывающего
    возможности сравнить «до» и «после».
    """
    delta = token_delta(turn)
    used = state.budget_used
    return state.model_copy(
        update={
            "budget_used": used.model_copy(
                update={
                    "tokens": used.tokens if delta is None else used.tokens + delta,
                    "wall_seconds": used.wall_seconds + elapsed_s,
                }
            )
        }
    )


def token_delta(turn: AgentTurn | None) -> int | None:
    """Расход токенов шага: `None` — «не сообщил», `0` — «сообщил ноль».

    Шов существует ради этого различия и только ради него. В `BudgetUsed`
    его выразить нечем (`tokens: int`), в арифметике оно исчезает (`+0` и
    «не прибавлять» дают один результат), поэтому единственное место, где
    неизвестность ещё отличима от нуля, — граница между `AgentTurn` и
    счётчиком. Сверни её к `turn.tokens_used or 0`, и «адаптер без
    token-метрик» превратился бы в «адаптер, который ничего не тратит».

    Отсутствие `turn` — тоже неизвестность, а не ноль: шаг, не звавший
    агента, о расходе токенов не сообщал ничего.
    """
    if turn is None:
        return None
    return turn.tokens_used
