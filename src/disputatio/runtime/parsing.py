"""Извлечение JSON-объекта из свободного текста агента ([DESIGN-005]).

Агент отвечает текстом, а не файлом: вокруг `review.json` почти всегда стоит
болтовня, а сам объект приходит то голым, то в ```json-фенсе. Разбирать это
регулярным выражением нельзя — `{` и `}` встречаются внутри строковых
литералов (`"claim": "a { b"`), и жадный/ленивый шаблон одинаково режет
объект не там.

Поэтому здесь два приёма. Первый — посимвольный счётчик скобок, знающий про
строковые литералы и escape-последовательности JSON. Второй — проверка, что
найденный кусок вообще разбирается как JSON-объект: сбалансированных скобок
мало, потому что ревьюер цитирует код, а `if (x) { return 1; }`
сбалансирован ничуть не хуже настоящего объекта.

Разбор здесь — про well-formedness, а не про схему: `json.loads` отвечает
на вопрос «это JSON?», а не «это `Review`?». Границы объекта и схемная
валидация по-прежнему не смешиваются — знания о полях `review.json` в
модуле нет, и функция возвращает **подстроку** исходного текста, а не
пересобранное значение (NFR-003). Разбор подстроки в модель — работа
pydantic, и только его. Ничего не интерпретируется как код: ни `eval`, ни
`exec`, ни `literal_eval`.

Модуль чист: ни I/O, ни времени, ни случайности — результат зависит только
от аргумента.
"""

import json
from typing import Final

from disputatio.runtime.errors import ReviewParseError

_OPEN: Final = "{"
_CLOSE: Final = "}"
_QUOTE: Final = '"'
_ESCAPE: Final = "\\"


def extract_json_object(text: str) -> str:
    """Извлекает первый top-level JSON-объект из текста агента.

    Поддерживает голый JSON и ```json-фенсы: фенс — просто текст вокруг
    объекта, и отдельной ветки под него нет, потому что ветка под каждый
    вид обёртки — это бесконечный список видов обёрток.

    Кандидатом считается каждая `{` слева направо, годным — первый
    кандидат, чьи скобки закрылись И который разбирается как JSON-объект.
    Оба условия нужны, и каждое отсекает свою форму прозы: незакрытая `{`
    («поставь `{` в начало») не балансируется, а закрытая цитата кода
    (`if (x) { return 1; }`) балансируется, но JSON'ом не является.

    Ни одного объекта — `ReviewParseError` ([DESIGN-020]): «агент ответил
    прозой» — это диагноз, который обязан дойти до пользователя строкой, а
    не превратиться в `None` и всплыть потом `ValidationError`'ом на
    пустом входе. Он же не должен превратиться в `ValidationError` на
    куске кода, выданном за ревью, — иначе схемный retry ([DESIGN-006])
    тратится на ответ, где схема ни при чём.
    """
    for start, char in enumerate(text):
        if char != _OPEN:
            continue
        end = _scan_object(text, start)
        if end is None:
            continue
        candidate = text[start:end]
        if _is_json_object(candidate):
            return candidate
    raise ReviewParseError(
        "вывод ревьюера не содержит JSON-объекта: ни голого, ни в ```json-фенсе"
    )


def _is_json_object(candidate: str) -> bool:
    """`candidate` — разбираемый непустой JSON-объект?

    Непустой: `{}` разбирается, но артефактом протокола не бывает ни один
    — все они несут как минимум `schema`. Пустой объект в прозе
    («issues будет `{}`») поэтому кандидатом не считается, иначе он
    перехватил бы разбор у настоящего ревью, стоящего следом.

    `ValueError` ловится целиком: `json.JSONDecodeError` — его подкласс, и
    перечислять подклассы поимённо значит однажды пропустить новый.
    """
    try:
        value = json.loads(candidate)
    except ValueError:
        return False
    return isinstance(value, dict) and bool(value)


def _scan_object(text: str, start: int) -> int | None:
    """Индекс за `}`, закрывающей объект из `start`; `None` — не закрылся.

    Внутри строкового литерала скобки не считаются вовсе, а `\\` съедает
    следующий символ целиком: без этого `"quote": "он написал \\"{\\""`
    закрыл бы литерал на экранированной кавычке и дальше считал бы скобки
    кода как скобки JSON.
    """
    depth = 0
    in_string = False
    escaped = False
    for index in range(start, len(text)):
        char = text[index]
        if in_string:
            if escaped:
                escaped = False
            elif char == _ESCAPE:
                escaped = True
            elif char == _QUOTE:
                in_string = False
            continue
        if char == _QUOTE:
            in_string = True
        elif char == _OPEN:
            depth += 1
        elif char == _CLOSE:
            depth -= 1
            if depth == 0:
                return index + 1
    return None
