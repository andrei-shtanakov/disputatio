"""Извлечение JSON-объекта из свободного текста агента ([DESIGN-005]).

Агент отвечает текстом, а не файлом: вокруг `review.json` почти всегда стоит
болтовня, а сам объект приходит то голым, то в ```json-фенсе. Разбирать это
регулярным выражением нельзя — `{` и `}` встречаются внутри строковых
литералов (`"claim": "a { b"`), и жадный/ленивый шаблон одинаково режет
объект не там.

Поэтому здесь ровно один приём: посимвольный счётчик скобок, знающий про
строковые литералы и escape-последовательности JSON. Он ничего не
интерпретирует — ни `eval`, ни `exec`, ни `literal_eval`, — и возвращает
**подстроку** исходного текста, а не пересобранное значение (NFR-003).
Разбор возвращённой подстроки в модель — работа pydantic, и только его:
схемная валидация и поиск границ объекта не смешиваются.

Модуль чист: ни I/O, ни времени, ни случайности — результат зависит только
от аргумента.
"""

from typing import Final

from disputatio.runtime.errors import ReviewParseError

_OPEN: Final = "{"
_CLOSE: Final = "}"
_QUOTE: Final = '"'
_ESCAPE: Final = "\\"


def extract_json_object(text: str) -> str:
    """Извлекает первый top-level JSON-объект из текста агента.

    Поддерживает голый JSON и ```json-фенсы: фенс — просто текст вокруг
    объекта, и отдельной ветки под него нет, потому что ветка под каждый
    вид обёртки — это бесконечный список видов обёрток.

    Кандидатом считается каждая `{` слева направо, годным — первый
    кандидат, чьи скобки закрылись. Незакрытая `{` в прозе («поставь `{`
    в начало») поэтому не отравляет разбор: она просто не балансируется, и
    поиск идёт дальше.

    Ни одного объекта — `ReviewParseError` ([DESIGN-020]): «агент ответил
    прозой» — это диагноз, который обязан дойти до пользователя строкой, а
    не превратиться в `None` и всплыть потом `ValidationError`'ом на
    пустом входе.
    """
    for start, char in enumerate(text):
        if char != _OPEN:
            continue
        end = _scan_object(text, start)
        if end is not None:
            return text[start:end]
    raise ReviewParseError(
        "вывод ревьюера не содержит JSON-объекта: ни голого, ни в ```json-фенсе"
    )


def _scan_object(text: str, start: int) -> int | None:
    """Индекс за `}`, закрывающей объект из `start`; `None` — не закрылся.

    Внутри строкового литерала скобки не считаются вовсе, а `\\` съедает
    следующий символ целиком: без этого `"quote": "он написал \\"{\\""`
    закрыл бы литерал на экранированной кавычке и дальше считал бы скобки
    кода как скобки JSON.
    """
    depth = 0
    in_string = False
    escaped = False
    for index in range(start, len(text)):
        char = text[index]
        if in_string:
            if escaped:
                escaped = False
            elif char == _ESCAPE:
                escaped = True
            elif char == _QUOTE:
                in_string = False
            continue
        if char == _QUOTE:
            in_string = True
        elif char == _OPEN:
            depth += 1
        elif char == _CLOSE:
            depth -= 1
            if depth == 0:
                return index + 1
    return None
